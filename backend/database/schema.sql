CREATE TABLE contracts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id               BIGINT NOT NULL REFERENCES players(id) ON DELETE RESTRICT,
    signing_team_id         BIGINT REFERENCES teams(id) ON DELETE RESTRICT,
    source_id               BIGINT REFERENCES data_sources(id) ON DELETE RESTRICT,
    external_id             TEXT,
    signed_on               DATE,
    start_season            SMALLINT NOT NULL REFERENCES seasons(start_year) ON DELETE RESTRICT,
    end_season              SMALLINT NOT NULL REFERENCES seasons(start_year) ON DELETE RESTRICT,
    term_years              SMALLINT NOT NULL,
    contract_type           VARCHAR(32),
    expiry_status           VARCHAR(8),
    total_value_cents       BIGINT,
    average_value_cents     BIGINT,
    is_entry_level          BOOLEAN NOT NULL DEFAULT FALSE,
    source_payload          JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT contracts_valid_seasons CHECK (end_season >= start_season),
    CONSTRAINT contracts_positive_term CHECK (term_years > 0),
    CONSTRAINT contracts_valid_expiry_status
        CHECK (expiry_status IS NULL OR expiry_status IN ('RFA', 'UFA')),
    CONSTRAINT contracts_nonnegative_value
        CHECK (total_value_cents IS NULL OR total_value_cents >= 0),
    CONSTRAINT contracts_nonnegative_average
        CHECK (average_value_cents IS NULL OR average_value_cents >= 0)
);

CREATE UNIQUE INDEX contracts_source_external_id_idx
    ON contracts (source_id, external_id)
    WHERE source_id IS NOT NULL AND external_id IS NOT NULL;

CREATE INDEX contracts_player_seasons_idx
    ON contracts (player_id, start_season, end_season);

CREATE TABLE contract_seasons (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id                 BIGINT NOT NULL REFERENCES contracts(id) ON DELETE CASCADE,
    season_start_year           SMALLINT NOT NULL REFERENCES seasons(start_year) ON DELETE RESTRICT,
    owning_team_id              BIGINT REFERENCES teams(id) ON DELETE RESTRICT,
    base_salary_cents           BIGINT,
    signing_bonus_cents         BIGINT,
    performance_bonus_cents     BIGINT,
    total_cash_cents            BIGINT,
    cap_hit_cents               BIGINT NOT NULL,
    cap_percentage              NUMERIC(9, 8),
    is_slide                    BOOLEAN NOT NULL DEFAULT FALSE,
    clauses                     JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT contract_seasons_contract_year_key
        UNIQUE (contract_id, season_start_year),
    CONSTRAINT contract_seasons_nonnegative_money
        CHECK (
            (base_salary_cents IS NULL OR base_salary_cents >= 0)
            AND (signing_bonus_cents IS NULL OR signing_bonus_cents >= 0)
            AND (performance_bonus_cents IS NULL OR performance_bonus_cents >= 0)
            AND (total_cash_cents IS NULL OR total_cash_cents >= 0)
            AND cap_hit_cents >= 0
        ),
    CONSTRAINT contract_seasons_nonnegative_cap_percentage
        CHECK (cap_percentage IS NULL OR cap_percentage >= 0)
);

CREATE INDEX contract_seasons_season_idx
    ON contract_seasons (season_start_year, contract_id);

CREATE TABLE games (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nhl_game_id         BIGINT NOT NULL UNIQUE,
    season_start_year   SMALLINT NOT NULL REFERENCES seasons(start_year) ON DELETE RESTRICT,
    game_type           SMALLINT NOT NULL,
    game_date           DATE NOT NULL,
    start_time_utc      TIMESTAMPTZ,
    away_team_id        BIGINT NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    home_team_id        BIGINT NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    venue               VARCHAR(200),
    game_state          VARCHAR(32),
    away_score          SMALLINT,
    home_score          SMALLINT,
    last_synced_at      TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT games_valid_game_type CHECK (game_type IN (1, 2, 3)),
    CONSTRAINT games_distinct_teams CHECK (away_team_id <> home_team_id),
    CONSTRAINT games_nonnegative_scores
        CHECK (
            (away_score IS NULL OR away_score >= 0)
            AND (home_score IS NULL OR home_score >= 0)
        )
);

CREATE INDEX games_schedule_idx
    ON games (season_start_year, game_type, start_time_utc);

CREATE TABLE ingestion_runs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id           BIGINT NOT NULL REFERENCES data_sources(id) ON DELETE RESTRICT,
    job_name            VARCHAR(120) NOT NULL,
    status              VARCHAR(16) NOT NULL DEFAULT 'running',
    started_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at         TIMESTAMPTZ,
    records_read        INTEGER NOT NULL DEFAULT 0,
    records_created     INTEGER NOT NULL DEFAULT 0,
    records_updated     INTEGER NOT NULL DEFAULT 0,
    records_skipped     INTEGER NOT NULL DEFAULT 0,
    error_message       TEXT,
    metadata            JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT ingestion_runs_valid_status
        CHECK (status IN ('running', 'succeeded', 'failed', 'cancelled')),
    CONSTRAINT ingestion_runs_nonnegative_counts
        CHECK (
            records_read >= 0
            AND records_created >= 0
            AND records_updated >= 0
            AND records_skipped >= 0
        )
);

CREATE INDEX ingestion_runs_recent_idx
    ON ingestion_runs (job_name, started_at DESC);

CREATE TABLE source_records (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingestion_run_id    BIGINT REFERENCES ingestion_runs(id) ON DELETE SET NULL,
    source_id           BIGINT NOT NULL REFERENCES data_sources(id) ON DELETE RESTRICT,
    entity_type         VARCHAR(64) NOT NULL,
    external_key        TEXT NOT NULL,
    payload_hash        VARCHAR(128) NOT NULL,
    payload             JSONB NOT NULL,
    fetched_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT source_records_version_key
        UNIQUE (source_id, entity_type, external_key, payload_hash)
);

CREATE INDEX source_records_lookup_idx
    ON source_records (source_id, entity_type, external_key, fetched_at DESC);

