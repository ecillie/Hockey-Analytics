CREATE TABLE seasons (
    start_year          SMALLINT PRIMARY KEY,
    end_year            SMALLINT NOT NULL,
    label               VARCHAR(9) NOT NULL UNIQUE,
    regular_start_date  DATE,
    regular_end_date    DATE,
    salary_cap_cents    BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT seasons_consecutive_years
        CHECK (end_year = start_year + 1),
    CONSTRAINT seasons_positive_salary_cap
        CHECK (salary_cap_cents IS NULL OR salary_cap_cents >= 0),
    CONSTRAINT seasons_valid_dates
        CHECK (
            regular_start_date IS NULL
            OR regular_end_date IS NULL
            OR regular_end_date >= regular_start_date
        )
);

