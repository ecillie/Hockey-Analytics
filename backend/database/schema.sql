CREATE TABLE teams (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nhl_team_id         INTEGER UNIQUE,
    nhl_franchise_id    INTEGER,
    abbreviation        VARCHAR(4) NOT NULL UNIQUE,
    name                VARCHAR(120) NOT NULL,
    city                VARCHAR(120),
    active              BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE players (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name          VARCHAR(100) NOT NULL,
    last_name           VARCHAR(100) NOT NULL,
    birth_date          DATE,
    primary_position    VARCHAR(3),
    shoots_catches      CHAR(1),
    nationality         VARCHAR(3),
    active              BOOLEAN NOT NULL DEFAULT TRUE,
    roster_status       roster_status NOT NULL DEFAULT 'UNKNOWN',
    roster_status_updated_at TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT players_valid_position
        CHECK (
            primary_position IS NULL
            OR primary_position IN ('C', 'LW', 'RW', 'D', 'G', 'F')
        ),
    CONSTRAINT players_valid_handedness
        CHECK (shoots_catches IS NULL OR shoots_catches IN ('L', 'R'))
);

CREATE INDEX players_name_idx
    ON players (LOWER(last_name), LOWER(first_name));

CREATE INDEX players_roster_status_idx
    ON players (roster_status);

