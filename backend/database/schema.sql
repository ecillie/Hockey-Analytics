-- TradeValue PostgreSQL schema.
--
-- Design rules:
--   * Player identity, performance, and contracts are independent timelines.
--   * External identifiers are retained so ingestion never relies on names.
--   * Money is stored in cents; percentages are stored as ratios (0.10 = 10%).
--   * Frequently modeled metrics are typed. Source-specific long-tail metrics
--     remain available in JSONB until they earn a stable typed column.

