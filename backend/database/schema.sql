    target_season               SMALLINT REFERENCES seasons(start_year) ON DELETE RESTRICT,
    actual_contract_season_id   BIGINT REFERENCES contract_seasons(id) ON DELETE SET NULL,
    position_group              VARCHAR(16) NOT NULL,
    predicted_aav_cents         BIGINT,
    predicted_cap_percentage    NUMERIC(9, 8),
    input_features              JSONB NOT NULL,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT predictions_valid_position_group
        CHECK (position_group IN ('forward', 'defense', 'goalie')),
    CONSTRAINT predictions_nonnegative_aav
        CHECK (predicted_aav_cents IS NULL OR predicted_aav_cents >= 0),
    CONSTRAINT predictions_nonnegative_cap_percentage
        CHECK (predicted_cap_percentage IS NULL OR predicted_cap_percentage >= 0)
);

CREATE INDEX predictions_player_history_idx
    ON predictions (player_id, created_at DESC);

CREATE INDEX predictions_model_idx
    ON predictions (model_version_id, created_at DESC);

COMMIT;
